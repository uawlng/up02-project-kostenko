-- Задание 1. Самый дорогой товар
SELECT наименование, цена
FROM Товар
ORDER BY цена DESC
LIMIT 1;

-- Задание 2. Самый дешёвый товар
SELECT наименование, цена
FROM Товар
ORDER BY цена ASC
LIMIT 1;

-- Задание 3. Товары одной категории (например, "Стол")
SELECT наименование, цена
FROM Товар
WHERE категория = 'Стол';

-- Задание 4. Поиск по названию (буква "о")
SELECT id, наименование, цена
FROM Товар
WHERE наименование LIKE '%о%';

-- Задание 5. Все заказы
SELECT id, дата, клиент, товар_id, количество
FROM Заказ;

-- Задание 6. Заказы клиента «Иванов Иван Иванович»
SELECT *
FROM Заказ
WHERE клиент = 'Иванов Иван Иванович';

-- Задание 7. JOIN — заказы с названиями товаров
SELECT Заказ.дата, Заказ.клиент, Товар.наименование, Заказ.количество
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 8. Общая сумма всех заказов
SELECT SUM(Товар.цена * Заказ.количество) AS итого
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;

-- Задание 9. Количество заказов по клиентам
SELECT клиент, COUNT(*) AS заказов
FROM Заказ
GROUP BY клиент;

-- Задание 10. Мой запрос
-- Что хочу получить: список товаров с ценой от 10000 до 40000,
-- отсортированный по возрастанию цены
SELECT наименование, цена
FROM Товар
WHERE цена BETWEEN 10000 AND 40000
ORDER BY цена ASC;